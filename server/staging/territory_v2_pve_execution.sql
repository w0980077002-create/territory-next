-- TERRITORY 2.0 ONLY. PRIVATE staging, never run on V1.
-- Immutable server-owned combat snapshot and atomic result+stage settlement.
-- Not an HTTP endpoint. Requires base schema, PvE protocol and stage progress.
-- No money, XP, items or paid functionality is issued by this migration.
begin;

create or replace function territory_v2.valid_pve_combatant(p jsonb)
returns boolean language plpgsql immutable set search_path=pg_catalog as $v2$
declare k text; n numeric;
begin
  if p is null or jsonb_typeof(p)<>'object' or
     (select count(*) from jsonb_object_keys(p))<>5 then return false; end if;
  foreach k in array array['hp','attack','defense','critBps','dodgeBps'] loop
    if jsonb_typeof(p->k)<>'number' then return false; end if;
    n:=(p->>k)::numeric;
    if n<>trunc(n) then return false; end if;
    if k='hp' and (n<1 or n>10000000) then return false; end if;
    if k='attack' and (n<1 or n>1000000) then return false; end if;
    if k='defense' and (n<0 or n>1000000) then return false; end if;
    if k in ('critBps','dodgeBps') and (n<0 or n>10000) then return false; end if;
  end loop;
  return true;
exception when others then return false;
end;
$v2$;

create or replace function territory_v2.valid_pve_rules(p jsonb)
returns boolean language plpgsql immutable set search_path=pg_catalog as $v2$
declare k text; n numeric;
begin
  if p is null or jsonb_typeof(p)<>'object' or
     (select count(*) from jsonb_object_keys(p))<>6 then return false; end if;
  foreach k in array array['maxTurns','enemyAttackEvery','defenseReductionBps',
      'criticalMultiplierBps','bossRageThresholdBps','bossRageMultiplierBps'] loop
    if jsonb_typeof(p->k)<>'number' then return false; end if;
    n:=(p->>k)::numeric;
    if n<>trunc(n) then return false; end if;
    if k='maxTurns' and (n<1 or n>2000) then return false; end if;
    if k='enemyAttackEvery' and (n<1 or n>20) then return false; end if;
    if k in ('defenseReductionBps','bossRageThresholdBps') and
      (n<0 or n>10000) then return false; end if;
    if k in ('criticalMultiplierBps','bossRageMultiplierBps') and
      (n<10000 or n>50000) then return false; end if;
  end loop;
  return true;
exception when others then return false;
end;
$v2$;

-- No invented stats or economy: a future V2 balance release must explicitly
-- configure each class+level and each campaign stage. Defaults grant nothing.
create table if not exists territory_v2.pve_class_profiles (
  class_id text not null check (class_id in ('berserker','runemage','ranger')),
  hero_level integer not null check (hero_level between 1 and 100000),
  stats jsonb not null check (territory_v2.valid_pve_combatant(stats)),
  primary key(class_id,hero_level)
);
create table if not exists territory_v2.pve_stage_profiles (
  chapter integer not null check (chapter between 1 and 5),
  wave integer not null check (wave between 1 and 20),
  enemy jsonb not null check (territory_v2.valid_pve_combatant(enemy)),
  is_boss boolean not null,
  primary key(chapter,wave)
);
-- Singleton prevents accidental selection between multiple enabled rulebooks.
create table if not exists territory_v2.pve_active_rules (
  singleton boolean primary key default true check (singleton),
  version text not null references territory_v2.pve_rulebooks(version)
);
create table if not exists territory_v2.pve_execution_snapshots (
  battle_id uuid primary key references territory_v2.battle_sessions(id) on delete restrict,
  snapshot jsonb not null check (jsonb_typeof(snapshot)='object'),
  snapshot_sha256 text not null check (snapshot_sha256 ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now()
);
create or replace function territory_v2.reject_pve_snapshot_mutation()
returns trigger language plpgsql security invoker set search_path=pg_catalog as $v2$
begin
  raise exception 'PVE_SNAPSHOT_IMMUTABLE' using errcode='23514';
end;
$v2$;
do $v2$
begin
  if not exists(select 1 from pg_trigger
      where tgrelid='territory_v2.pve_execution_snapshots'::regclass
      and tgname='pve_snapshot_immutable') then
    create trigger pve_snapshot_immutable before update or delete
      on territory_v2.pve_execution_snapshots for each row
      execute function territory_v2.reject_pve_snapshot_mutation();
  end if;
end;
$v2$;

do $v2$
declare t text;
begin
  foreach t in array array['pve_class_profiles','pve_stage_profiles',
      'pve_active_rules','pve_execution_snapshots'] loop
    execute format('alter table territory_v2.%I enable row level security',t);
    execute format('revoke all on table territory_v2.%I from public,anon,authenticated',t);
    execute format('grant select,insert,update,delete on territory_v2.%I to service_role',t);
  end loop;
end;
$v2$;

-- Must be called ONLY after verifying signed Telegram initData on V2 server.
-- p_seed is generated by cryptographic RNG on the server; NEVER by browser.
-- Character is locked before the battle (same lock order as existing protocol).
create or replace function territory_v2.begin_pve_execution(
  p_telegram_user_id bigint, p_battle_id uuid, p_seed bigint
) returns jsonb
language plpgsql security invoker set search_path=pg_catalog as $v2$
declare
  v_player uuid;
  v_char territory_v2.characters%rowtype;
  v_existing jsonb;
  v_hero jsonb;
  v_stage territory_v2.pve_stage_profiles%rowtype;
  v_rules territory_v2.pve_rulebooks%rowtype;
  v_snapshot jsonb;
  v_hash text;
begin
  if p_telegram_user_id is null or p_telegram_user_id<=0 or
     p_battle_id is null or p_seed is null or p_seed<1 or p_seed>4294967295 then
    raise exception 'PVE_EXECUTION_INVALID_REQUEST' using errcode='22023';
  end if;
  select id into v_player from territory_v2.players
    where telegram_user_id=p_telegram_user_id;
  if not found then
    raise exception 'PVE_EXECUTION_UNREGISTERED' using errcode='23503';
  end if;
  select * into v_char from territory_v2.characters
    where player_id=v_player for update;
  if not found then
    raise exception 'PVE_EXECUTION_NO_CHARACTER' using errcode='23503';
  end if;

  -- Same server battle ID replays its original seed/rules/hero, even after
  -- class/rules profiles are changed. Never regenerate on retry.
  select e.snapshot into v_existing
    from territory_v2.pve_execution_snapshots e
    join territory_v2.battle_sessions b on b.id=e.battle_id
    where e.battle_id=p_battle_id and b.player_id=v_player
      and b.character_id=v_char.id;
  if found then return v_existing; end if;
  if exists(select 1 from territory_v2.battle_sessions
      where id=p_battle_id) then
    raise exception 'PVE_EXECUTION_BATTLE_ID_CONFLICT' using errcode='23505';
  end if;
  if v_char.stage_chapter not between 1 and 5 or
     v_char.stage_wave not between 1 and 20 then
    raise exception 'PVE_EXECUTION_INVALID_STAGE' using errcode='22023';
  end if;
  if exists(select 1 from territory_v2.pve_stage_clears
      where player_id=v_player and chapter=v_char.stage_chapter
        and wave=v_char.stage_wave) then
    raise exception 'PVE_EXECUTION_STAGE_ALREADY_CLEARED' using errcode='23514';
  end if;

  select stats into v_hero from territory_v2.pve_class_profiles
    where class_id=v_char.class_id and hero_level=v_char.level;
  if not found or not territory_v2.valid_pve_combatant(v_hero) then
    raise exception 'PVE_EXECUTION_HERO_PROFILE_MISSING' using errcode='22023';
  end if;
  select * into v_stage from territory_v2.pve_stage_profiles
    where chapter=v_char.stage_chapter and wave=v_char.stage_wave;
  if not found then
    raise exception 'PVE_EXECUTION_STAGE_PROFILE_MISSING' using errcode='22023';
  end if;
  select r.* into v_rules from territory_v2.pve_active_rules a
    join territory_v2.pve_rulebooks r on r.version=a.version
    where a.singleton=true and r.enabled=true;
  if not found or not territory_v2.valid_pve_rules(v_rules.config) then
    raise exception 'PVE_EXECUTION_RULES_MISSING' using errcode='22023';
  end if;
  v_snapshot:=jsonb_build_object(
    'battleId',p_battle_id::text,
    'stageId',format('chapter%s.wave%s',v_char.stage_chapter,v_char.stage_wave),
    'classId',v_char.class_id,
    'isBoss',v_stage.is_boss,
    'hero',v_hero,
    'enemy',v_stage.enemy,
    'seed',p_seed,
    'rules',v_rules.config||jsonb_build_object('version',v_rules.version)
  );
  v_hash:=encode(sha256(convert_to(v_snapshot::text,'UTF8')),'hex');
  perform territory_v2.begin_authoritative_pve(
    v_player,v_char.id,p_battle_id,v_rules.version,v_hash
  );
  insert into territory_v2.pve_execution_snapshots
    (battle_id,snapshot,snapshot_sha256) values(p_battle_id,v_snapshot,v_hash);
  return v_snapshot;
end;
$v2$;

-- The returned snapshot CONTAINS THE SECRET SEED. Private service only.
-- NEVER attach this function to the public Telegram gateway.
create or replace function territory_v2.read_pve_execution(
  p_telegram_user_id bigint,p_battle_id uuid
) returns jsonb language sql stable security invoker set search_path=pg_catalog as $v2$
  select e.snapshot
  from territory_v2.pve_execution_snapshots e
  join territory_v2.battle_sessions b on b.id=e.battle_id
  join territory_v2.players p on p.id=b.player_id
  where p.telegram_user_id=p_telegram_user_id and b.id=p_battle_id
  limit 1;
$v2$;

-- Settlement must be one SQL transaction: receipt, battle and optional
-- first-clear progress. Does not grant XP, gold, diamonds or items.
create or replace function territory_v2.finish_pve_execution(
  p_telegram_user_id bigint,p_battle_id uuid,
  p_resolve_receipt uuid,p_clear_receipt uuid,
  p_trace_sha256 text,p_outcome text,p_reason text,p_turns integer
) returns jsonb language plpgsql security invoker set search_path=pg_catalog as $v2$
declare
  v_player uuid;
  v_char uuid;
  v_battle territory_v2.battle_sessions%rowtype;
  v_hash text;
  v_result jsonb;
  v_clear jsonb;
begin
  if p_telegram_user_id is null or p_telegram_user_id<=0 or
     p_battle_id is null or p_resolve_receipt is null or
     p_clear_receipt is null or p_resolve_receipt=p_clear_receipt then
    raise exception 'PVE_FINISH_INVALID_REQUEST' using errcode='22023';
  end if;
  select b.player_id,b.character_id into v_player,v_char
    from territory_v2.battle_sessions b where b.id=p_battle_id;
  if not found then
    raise exception 'PVE_FINISH_NOT_FOUND' using errcode='23503';
  end if;
  -- Always lock character first to match begin and stage_clear.
  perform 1 from territory_v2.characters
    where id=v_char and player_id=v_player for update;
  select * into v_battle from territory_v2.battle_sessions
    where id=p_battle_id for update;
  if not exists(select 1 from territory_v2.players p
      where p.id=v_player and p.telegram_user_id=p_telegram_user_id) then
    raise exception 'PVE_FINISH_NOT_OWNED' using errcode='23503';
  end if;
  select e.snapshot_sha256 into v_hash from territory_v2.pve_execution_snapshots e
    where e.battle_id=p_battle_id;
  if not found or not exists(select 1 from territory_v2.pve_combat_records r
      where r.battle_id=p_battle_id and r.snapshot_sha256=v_hash) then
    raise exception 'PVE_FINISH_SNAPSHOT_MISMATCH' using errcode='23514';
  end if;
  v_result:=territory_v2.record_authoritative_pve_result(
    p_battle_id,p_resolve_receipt,p_trace_sha256,p_outcome,p_reason,p_turns);
  if p_outcome='victory' then
    v_clear:=territory_v2.record_authoritative_stage_clear(
      p_battle_id,p_clear_receipt);
  end if;
  return jsonb_build_object('resolution',v_result,'clear',v_clear);
end;
$v2$;

do $v2$
declare f text;
begin
  foreach f in array array[
    'valid_pve_combatant(jsonb)',
    'valid_pve_rules(jsonb)',
    'reject_pve_snapshot_mutation()',
    'begin_pve_execution(bigint,uuid,bigint)',
    'read_pve_execution(bigint,uuid)',
    'finish_pve_execution(bigint,uuid,uuid,uuid,text,text,text,integer)'
  ] loop
    execute format('revoke all on function territory_v2.%s from public,anon,authenticated',f);
    execute format('grant execute on function territory_v2.%s to service_role',f);
  end loop;
end;
$v2$;
commit;
